# Operadores de pertencencia (in/not in)
# in = en 
# Si la palabra o lo que queremos saber esta sale True si no sale False 
# Ej: print ("Hola" <- esta palabra es la que quiero buscar, 
# in<- la variable y bienvenida<- es donde quiero buscar)

nombre = "Eddier"
bienvenido = f"!Hola  {nombre} , ¿Como estas?"

print( "Hola" in bienvenido) # True


# Si quiero decir no esta Hola se utiliza not 

